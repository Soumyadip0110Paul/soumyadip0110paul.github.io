"""
Writes images/photo-list.js: a list of every photo inside the images/ folder.

The website normally asks GitHub which photos exist, so this file is a BACKUP.
Run it whenever you add or remove photos if:
  - you open index.html directly from your computer (double-click), or
  - you host the site somewhere other than GitHub Pages, or
  - photos sometimes fail to load on GitHub (GitHub limits free requests).

Usage (from the website folder):   python update_photo_list.py
No installs needed.
"""
from pathlib import Path
import json

ROOT = Path(__file__).resolve().parent
EXTS = {".jpg", ".jpeg", ".png", ".webp", ".gif", ".avif", ".svg"}

paths = sorted(
    p.relative_to(ROOT).as_posix()
    for p in (ROOT / "images").rglob("*")
    if p.is_file() and p.suffix.lower() in EXTS and "_originals" not in p.as_posix()
)
(ROOT / "images" / "photo-list.js").write_text(
    "// Generated by update_photo_list.py. Re-run it after adding or removing photos.\n"
    "window.PHOTO_LIST = " + json.dumps(paths, indent=1) + ";\n",
    encoding="utf-8",
)
print(f"Saved {len(paths)} photos to images/photo-list.js")
for p in paths:
    print("  ", p)
